function result=run_m1_pl_own_v1(b)
%RUN_M1_PL_OWN_V1 Execute one explicit own-input M1 search or closure.
ctx=b.context;cfg=b.caseConfig;
assert(strcmp(cfg.reactor,b.reactor) && ctx.phaseAudit.responseLeakage==0 && ...
    max(ctx.observationTimes_d)==94 && numel(ctx.observed_ug_L)==33 && ...
    all(isnan(ctx.forcingData.Cout_ug_L)), ...
    'JWPE:Own:Phase','Invalid I-II context.');
assert(isfield(cfg,'catalogSHA256') && strcmp(cfg.catalogSHA256,b.catalogSHA256), ...
    'JWPE:Own:Identity','Case/catalogue identity mismatch.');
out=jwpe_own_output_v1(b.folder);
m1_atomic_v1(fullfile(out,'identity.mat'),b.identity,'mat',false);
m1_atomic_v1(fullfile(out,'configuration.mat'),cfg,'mat',false);
try
    switch b.analysis
        case 'pl_m1_free'
            assert(strcmp(cfg.role,'CONDITIONAL_SEARCH'), ...
                'JWPE:Own:Role','Use explicit closure analysis for closures.');
            result=jwpe_m1_pl_search(ctx,cfg,out);
        case 'pl_m1_free_closure'
            assert(strcmp(cfg.role,'CLOSURE_ANCHOR_REUSE'), ...
                'JWPE:Own:Role','Closure role mismatch.');
            result=jwpe_m1_pl_closure(ctx,cfg,out);
        case 'pl_m1_fixed'
            assert(~strcmp(cfg.role,'FIXED_KD_CLOSURE'), ...
                'JWPE:Own:Role','Closure requires its separate entry.');
            result=jwpe_fixed_search_v1(ctx,cfg,out);
        case 'pl_m1_fixed_closure'
            assert(strcmp(cfg.role,'FIXED_KD_CLOSURE') && ...
                ~strcmp(cfg.anchorPolicy,'STOP_RECHECK_IMPROVEMENT_GT_5E-4'), ...
                'JWPE:Own:Closure','Focal profile cannot launch a closure.');
            anchor=b.anchor;candidate=b.candidate;
            assert(strcmp(anchor.role,'ANCHOR_SEARCH') && strcmp(anchor.status,'COMPLETE_REVIEW_REQUIRED') && ...
                strcmp(candidate.status,'COMPLETE_REVIEW_REQUIRED') && ...
                strcmp(anchor.catalogSHA256,cfg.catalogSHA256) && ...
                strcmp(candidate.catalogSHA256,cfg.catalogSHA256) && ...
                abs(anchor.recheckDelta)<=5e-4 && abs(candidate.recheckDelta)<=5e-4 && ...
                anchor.fixedKd==.02 && candidate.fixedKd==.02 && ...
                strcmp(anchor.reactor,b.reactor) && strcmp(candidate.reactor,b.reactor) && ...
                candidate.nll<anchor.nll-5e-4, ...
                'JWPE:Own:Closure','Invalid closure origins.');
            assert(~strcmp(candidate.anchorPolicy,'STOP_RECHECK_IMPROVEMENT_GT_5E-4'), ...
                'JWPE:Own:Closure','Focal candidate disables closure.');
            cfg.initialTheta=candidate.theta;cfg.baseTheta=candidate.theta;
            assert(cfg.initialTheta(1)==.020 && ...
                all(cfg.initialTheta(cfg.freeIndices)>=cfg.lower & cfg.initialTheta(cfg.freeIndices)<=cfg.upper), ...
                'JWPE:Own:Closure','Closure seed outside declared support.');
            m1_atomic_v1(fullfile(out,'effective_closure_configuration.mat'),cfg,'mat',false);
            reservation=fullfile(fileparts(out),['CLOSURE_' b.campaignID '_' b.reactor '.json']);
            m1_atomic_v1(reservation,jsonencode(b.identity),'text',false);
            result=jwpe_fixed_closure_v1(ctx,cfg,out);result.fixedKd=.02;
        otherwise
            error('JWPE:Own:Analysis','Unknown M1 profile operation.');
    end
    m1_atomic_v1(fullfile(out,'result.mat'),result,'mat',false);
    files={'identity.mat','configuration.mat','result.mat'};
    if isfile(fullfile(out,'effective_closure_configuration.mat'))
        files{end+1}='effective_closure_configuration.mat';
    end
    jwpe_capacity_manifest(out,files);
catch ME
    m1_atomic_v1(fullfile(out,'STOP.json'),jsonencode(struct('identifier',ME.identifier, ...
        'message',ME.message,'retryAuthorized',false)),'text',false);
    rethrow(ME)
end
end
