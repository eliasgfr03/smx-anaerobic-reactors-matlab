function result=run_selection_own_v1(b)
%RUN_SELECTION_OWN_V1 Generate a new joint selection from explicit chains.
cfg=b.config;reactor=b.reactor;chains=b.chains;
assert(cfg.chains==4 && iscell(chains) && numel(chains)==4 && ...
    cfg.drawsPerReactor==4*cfg.strataPerChain, ...
    'JWPE:Own:Selection','Invalid balanced selection dimensions.');
for c=1:4
    assert(isequal(size(chains{c}),[cfg.(reactor).rowsPerChain 7]) && ...
        isreal(chains{c}) && all(isfinite(chains{c}),'all') && ...
        cfg.strataPerChain*cfg.(reactor).stratumWidth==size(chains{c},1), ...
        'JWPE:Own:Selection','Invalid physical chain/stratum sizes.');
    cfg.traceHashes.(reactor)(c)=string(m1_hash_v1(typecast(chains{c}(:),'uint8'),'bytes'));
end
assert(isequal(string(cfg.names(:)), ...
    ["Kd";"kb";"kG";"tinf";"Ai";"sigmaA";"sigmaP"]), ...
    'JWPE:Own:Selection','Seven-column joint physical order required.');
if strcmp(b.mode,'production')
    assert(b.chainCertification.warmupExcluded && b.chainCertification.certified && ...
        cfg.drawsPerReactor==500 && cfg.strataPerChain==125, ...
        'JWPE:Own:Certification','Production selection needs certified chains and 500 balanced draws.');
    d=b.chainCertification.diagnostics;
    assert(istable(d) && height(d)==7 && ...
        isequal(string(d.Parameter(:)),string(cfg.names(:))) && ...
        all(isfinite(d{:,{'Rhat','BulkESS','TailESS'}}),'all') && ...
        all(d.Rhat<1.01 & d.BulkESS>400 & d.TailESS>400), ...
        'JWPE:Own:Certification','Production chain criteria not met.');
else
    assert(b.chainCertification.warmupExcluded && ~b.chainCertification.certified, ...
        'JWPE:Own:Certification','Test chains must remain uncertified.');
end
folder=jwpe_own_output_v1(b.folder);
[selected,selection]=ppu_select_v1(reactor,chains,cfg);
result=struct('selected',selected,'selection',selection,'identity',b.identity, ...
    'reactor',reactor,'mode',b.mode,'certified',strcmp(b.mode,'production'));
m1_atomic_v1(fullfile(folder,'selected.mat'),result,'mat',false);
m1_atomic_v1(fullfile(folder,'selected.csv'),selected,'table',false);
jwpe_closed_source('close',folder,{'selected.mat','selected.csv'});
end
