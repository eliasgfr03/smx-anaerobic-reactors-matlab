function ctx = capacity_inputs_own_v1(b,onBudget)
%JWPE_CAPACITY_INPUTS Phase I-II context and guarded simulator handles.
% Construction reads data/settings/references but executes no model or score.
% G1/A1 retain separate exact six-coordinate caches. LOG2 retains no cache.
% A raw attempt is reserved before integration, including failed attempts.
% Returned state-invalid search trials reach the unchanged source evaluator;
reactor=b.reactor;
reactor=upper(string(reactor));
assert(isscalar(reactor) && any(reactor==["CS","PF"]), ...
    'JWPE:Capacity:Scope','Select one reactor, CS or PF.');
assert(isempty(onBudget) || isa(onBudget,'function_handle'), ...
    'JWPE:Capacity:Inputs','Invalid budget callback.');
core=b.core; base=b.capacityBase;
input=b.context;
assert(numel(input.observed_ug_L)==33 && all(input.observed_ug_L>core.observation.lod_ug_L) ...
    && max(input.observationTimes_d)==94 && height(input.forcingData)==33 ...
    && all(isnan(input.forcingData.Cout_ug_L)), ...
    'JWPE:Capacity:Phase','Invalid Phase I-II response/forcing separation.');
thetaRef=double(b.thetaRef(:).');
names={'G1','A1','LOG2'};
budgets=struct();
for i=1:3; budgets.(names{i})=jwpe_oem_budget('create',struct(),51); end
if reactor=="CS"; engine=@CS_simulate_model; else; engine=@PF_simulate_model; end
settings=input.settings; forcing=input.forcingData; times=input.observationTimes_d;
[g1,gs,gc]=jwpe_inf_make_forward_cache(@(x)raw('G1',x,false),core.cache.maxEntries);
[a1,as,ac]=jwpe_inf_make_forward_cache(@(x)raw('A1',x,false),core.cache.maxEntries);
ctx=struct('reactor',char(reactor),'dataFile',input.dataFile, ...
    'dataForcing',forcing,'settings',settings,'calibrationTimes_d',times, ...
    'calibrationObserved_ug_L',input.observed_ug_L,'nCalibrationObs',33, ...
    'nCalibrationCensored',0,'thetaRef',thetaRef,'harmonization',input.harmonization, ...
    'phaseAudit',struct('version',base.calibrationPolicyRequired, ...
    'countPhaseI',17,'countPhaseII',16,'countPhaseIII',17,'countCalibration',33, ...
    'countValidation',17,'calibrationMaxTime_d',94,'validationMinTime_d',103), ...
    'G1',struct('simulate',g1,'simulateRaw',@(x)raw('G1',x,true), ...
    'getCacheStats',gs,'clearCache',gc), ...
    'A1',struct('simulate',a1,'simulateRaw',@(x)raw('A1',x,true), ...
    'getCacheStats',as,'clearCache',ac), ...
    'LOG2',struct('simulateRaw',@(x,recheck)raw('LOG2',x,recheck)), ...
    'getRawBudgets',@read_budgets);

    function current=read_budgets()
        current=budgets;
    end

    function sim=raw(model,x,recheck)
        if strcmp(model,'LOG2')
            simulate=@()jwpe_03b_log2_simulate_model_v1(reactor,'LOG2',x, ...
                forcing,settings,times,false);
        else
            simulate=@()engine(jwpe_inf_native_to_engine(x),forcing,settings,times,false);
        end
        [sim,budgets.(model)]=jwpe_capacity_raw_attempt(budgets.(model), ...
            50+double(recheck),simulate,33,core.quality.minimumStateTolerance, ...
            logical(recheck),@(b)record_budget(model,b));
    end
    function record_budget(model,b)
        budgets.(model)=b;
        notify();
    end
    function notify()
        if ~isempty(onBudget); onBudget(budgets); end
    end
end
