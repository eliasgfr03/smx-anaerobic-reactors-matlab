function runs=jwpe_read_native_pl_v1(b)
%JWPE_READ_NATIVE_PL_V1 Read only explicit own-run results/configurations.
bindings=b.nativeRuns;runs=cell(numel(bindings),1);
for k=1:numel(bindings)
    item=bindings(k);
    assert(strcmp(m1_hash_v1(item.resultFile,'file'),item.resultSHA256) && ...
        strcmp(m1_hash_v1(item.configFile,'file'),item.configSHA256), ...
        'JWPE:Own:Identity','PL result/configuration identity mismatch.');
    q=load(item.resultFile,'payload');p=q.payload;
    q=load(item.configFile,'payload');cfg=q.payload;
    if isfield(cfg,'caseConfig'),cfg=cfg.caseConfig;end
    if strcmp(b.model,'M0')
        assert(isfield(p,'endpoint') && isfield(p,'identity') && isequaln(p.identity,b.identity), ...
            'JWPE:Own:Identity','M0 input/method/code identity mismatch.');
        e=p.endpoint;
        assert(strcmp(e.status,'PASS') && e.recheckPASS && ...
            ~strcmp(e.category,'SUPPORT_DIAGNOSTIC') && abs(e.recheckDelta)<=5e-4 && ...
            e.rawLedger.rawFailed==0 && ~e.rawLedger.pending && ...
            e.rawLedger.rawAttempts<=e.rawLedger.hardMax, ...
            'JWPE:Own:Eligibility','M0 result not independently eligible.');
        role='CONDITIONAL';if strcmp(cfg.map,'anchor'),role='ANCHOR';end
        r=struct('caseId',e.caseID,'reactor',e.reactor,'theta',e.theta,'nll',e.nll, ...
            'role',role,'status',e.status,'anchorPolicy','STOP_RECHECK_IMPROVEMENT_GT_5E-4');
    else
        r=p;
        assert(all(isfield(item,{'identityFile','identitySHA256'})) && ...
            strcmp(m1_hash_v1(item.identityFile,'file'),item.identitySHA256), ...
            'JWPE:Own:Identity','Explicit M1 input/method/code identity binding required.');
        identity=load(item.identityFile,'payload');
        assert(isfield(identity,'payload') && isequaln(identity.payload,b.identity), ...
            'JWPE:Own:Identity','Mixed M1 input/method/code identities.');
        if startsWith(r.status,'HOLD') || startsWith(r.status,'STOP')
            runs{k}=r;continue
        end
        assert(strcmp(r.status,'COMPLETE_REVIEW_REQUIRED') && r.officialEligible && ...
            r.phaseIIIExcluded && r.maxHorizon_d==94 && ...
            strcmp(r.catalogSHA256,b.catalogSHA256) && ...
            strcmp(r.catalogSHA256,cfg.catalogSHA256) && ...
            abs(r.recheckDelta)<=cfg.recheckToleranceNLL && ...
            r.counts.counts.failures==0 && r.counts.counts.rechecks==1 && ...
            r.counts.counts.rawForwards<=cfg.hardBudget && ...
            r.counts.counts.sigmaInnerCountsComplete, ...
            'JWPE:Own:Eligibility','M1 result not independently eligible.');
        if isfield(cfg,'fixedIndex') && cfg.fixedIndex>0
            assert(r.theta(cfg.fixedIndex)==cfg.fixedValue, ...
                'JWPE:Own:Coordinate','Fixed parameter changed.');
        end
        if strcmp(b.model,'M1_FIXED')
            assert(r.fixedKd==.020 && r.theta(1)==.020,'JWPE:Own:FixedKd','Kd is not fixed.');
        end
    end
    assert(strcmp(r.caseId,cfg.id) && strcmp(r.reactor,b.reactor) && ...
        all(isfinite(r.theta)) && isfinite(r.nll), ...
        'JWPE:Own:Identity','Mixed case/reactor or invalid endpoint.');
    runs{k}=r;
end
ids=cellfun(@(r)string(r.caseId),runs);
assert(numel(unique(ids))==numel(ids),'JWPE:Own:Identity','Duplicate result origin.');
end
