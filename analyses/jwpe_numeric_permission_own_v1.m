function permission=jwpe_numeric_permission_own_v1(b)
permission=b.numericPolicy;
required={'reactor','inputFiles','codeFiles','G1CallsMax','activityQuantileCallsMax', ...
    'PearsonCallsMax','histcountCallsMax','diagnosticCallsMax','externalQuantileCallsMax', ...
    'R2FlagCallsMax','R2Threshold','R2Comparator'};
assert(all(isfield(permission,required)) && strcmp(permission.reactor,b.reactor), ...
    'JWPE:Own:Numeric','Explicit numerical input/policy fields missing.');
files=permission.inputFiles;
assert(~isempty(files) && numel(unique(string({files.path})))==numel(files), ...
    'JWPE:Own:Numeric','Numeric inputs must be explicitly unique.');
for k=1:numel(files)
    info=dir(files(k).path);
    assert(isscalar(info) && info.bytes==files(k).bytes && ...
        strcmp(m1_hash_v1(files(k).path,'file'),files(k).sha256), ...
        'JWPE:Own:Identity','Numeric input identity mismatch.');
end
end
