function route=jwpe_own_validate_v1(b)
%JWPE_OWN_VALIDATE_V1 Validate explicit inputs without executing any kernel.
required={'schemaVersion','analysis','reactor','mode','runID','folder','identity'};
assert(isstruct(b) && isscalar(b) && all(isfield(b,required)) && ...
    strcmp(b.schemaVersion,'JWPE_OWN_EXECUTION_v1') && ...
    ismember(string(b.mode),["test","production"]), ...
    'JWPE:Own:Schema','Invalid own-input execution bundle.');
assert(~isempty(regexp(b.runID,'^[A-Za-z][A-Za-z0-9_-]{0,31}$','once')) && ...
    ismember(string(b.reactor),["CS","PF","ASBR","APBR","R1GAC","R2PU","joint"]), ...
    'JWPE:Own:Identity','Invalid run or reactor ID.');
assert(isstruct(b.identity) && isscalar(b.identity) && ...
    all(isfield(b.identity,{'datasetID','methodID','codeHash'})) && ...
    all(strlength(string({b.identity.datasetID,b.identity.methodID,b.identity.codeHash}))>0), ...
    'JWPE:Own:Identity','Explicit dataset/method/code identities required.');
route=jwpe_own_route_v1(b.analysis,b.reactor);
joint=ismember(string(b.analysis),["observation_error_joint","capacity_joint"]);
assert(joint==strcmp(b.reactor,'joint'), ...
    'JWPE:Own:Reactor','Joint analyses require the joint reactor label only.');
assert(all(isfield(b,route.requiredFields)), ...
    'JWPE:Own:Inputs','Analysis-specific explicit inputs are missing.');
assert(isscalar(string(b.folder)) && strlength(string(b.folder))>0 && ...
    java.io.File(char(b.folder)).isAbsolute(), ...
    'JWPE:Own:Output','Explicit absolute output folder required.');
assert(~isfile(b.folder),'JWPE:Own:Output','Output is a file.');
if isfolder(b.folder)
    assert(isfield(b,'action') && strcmp(b.action,'resume') && ...
        ismember(string(b.analysis),["calibration_m1_fixed","mcmc"]), ...
        'JWPE:Own:Overwrite','Existing folder is not an explicit resumable run.');
    file=fullfile(b.folder,'execution_mode.json');
    assert(isfile(file),'JWPE:Own:Resume','Original execution mode record missing.');
    m=jsondecode(fileread(file));
    assert(strcmp(m.mode,b.mode) && strcmp(m.analysis,b.analysis) && ...
        strcmp(m.reactor,b.reactor) && strcmp(m.codeHash,b.identity.codeHash), ...
        'JWPE:Own:Resume','Mode, analysis, reactor or code changed on resume.');
end
if isfield(b,'context') && isfield(b.context,'forcingData')
    f=b.context.forcingData;
    assert(~ismember('Cout_ug_L',f.Properties.VariableNames) || all(isnan(f.Cout_ug_L)), ...
        'JWPE:Own:Leakage','Responses cannot be stored in forcing.');
end
inferential=ismember(string(b.analysis),["calibration_m1_fixed","capacity_g1_a1", ...
    "capacity_log2","pl_m0","pl_m1_free","pl_m1_fixed","pl_m1_free_closure", ...
    "pl_m1_fixed_closure","gsa","mcmc","ofl_calibration","ofl_g1_screen"]);
if inferential && isfield(b,'context') && isfield(b.context,'observationTimes_d')
    assert(max(b.context.observationTimes_d)<=94, ...
        'JWPE:Own:Leakage','Holdout responses cannot enter inference.');
end
if strcmp(b.analysis,'pl_m0')
    assert(all(b.observations.Time_d<=94) && all(isnan(b.forcing.Cout_ug_L)), ...
        'JWPE:Own:Leakage','M0 inference requires I-II responses and response-free forcing.');
end
if strcmp(b.analysis,'calibration_m1_fixed')
    assert(strcmp(b.inputs.cfg.reactor,b.reactor) && ...
        b.inputs.context.phaseAudit.responseLeakage==0 && ...
        max(b.inputs.context.observationTimes_d)<=94, ...
        'JWPE:Own:Leakage','M1 input context mismatch.');
end
if strcmp(b.analysis,'pl_finalize')
    assert(b.D95==3.84145882069412 && ...
        ismember(string(b.model),["M0","M1_FREE","M1_FIXED"]), ...
        'JWPE:Own:Finalizer','Profile model or threshold mismatch.');
end
end
