function endpoint = jwpe_pl_m0_endpoint(caseConfig,opt,catalogue,ledger)
%JWPE_PL_M0_ENDPOINT Schema/anchor guard; uses already computed optimizer values.
% Does not invoke likelihood, model, optimizer, or derive a confidence interval.
assert(opt.recheckPASS && isfinite(opt.bestObjective) && opt.recheck.valid ...
    && isfinite(opt.recheckObjective) && isfinite(opt.recheckDelta) ...
    && ledger.rawFailed==0 && ~ledger.pending && ledger.rawAttempts>=1 ...
    && ledger.rawAttempts<=ledger.hardMax, ...
    'JWPE:PL:Endpoint','Invalid optimizer endpoint or ledger.');
theta=double(opt.recheck.thetaNative(:).');
assert(numel(theta)==6 && all(isfinite(theta)), ...
    'JWPE:PL:Endpoint','Malformed native endpoint.');
if ~strcmp(caseConfig.map,'anchor')
    names={'Kd','kb','krev','kG','tinf','Ai'};
    selected=strcmp(names,caseConfig.profile);
    assert(nnz(selected)==1,'JWPE:PL:Endpoint','Invalid profile name.');
    assert(abs(theta(selected)-caseConfig.fixedValue)<=1e-12, ...
        'JWPE:PL:Endpoint','Fixed coordinate changed.');
end
challenge=opt.bestObjective<catalogue.anchor.nll-catalogue.anchorChallengeTolerance;
status='PASS';
if challenge; status='ANCHOR_CHALLENGE'; end
endpoint=struct('schema','JWPE_PL_M0_ENDPOINT_v1','reactor','CS', ...
    'caseID',caseConfig.id,'profile',caseConfig.profile,'category',caseConfig.category, ...
    'fixedValue',caseConfig.fixedValue,'theta',theta,'nll',opt.bestObjective, ...
    'sigmaA',opt.recheck.errorFit.sigmaA,'sigmaP',opt.recheck.errorFit.sigmaP, ...
    'recheckNLL',opt.recheckObjective,'recheckDelta',opt.recheckDelta, ...
    'recheckPASS',opt.recheckPASS,'anchorNLL',catalogue.anchor.nll, ...
    'contextID',catalogue.contextID,'rawLedger',ledger,'status',status);
end
