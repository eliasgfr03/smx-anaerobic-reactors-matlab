function options = ofl_options_v1(kind,checkpoint)
%OFL_OPTIONS_V1 Constructs approved options only; does not invoke optimizers.
if strcmp(kind,'LOCAL')
    options = optimoptions('patternsearch','Display','iter','Algorithm','classic', ...
        'PollMethod','GPSPositiveBasis2N','UseCompletePoll',true,'ScaleMesh',false, ...
        'InitialMeshSize',.001,'MaxMeshSize',.008,'MeshExpansionFactor',2, ...
        'MeshContractionFactor',.5,'MeshTolerance',5e-5,'SearchFcn',[], ...
        'UseParallel',false,'UseVectorized',false,'MaxFunctionEvaluations',125);
else
    assert(ismember(kind,{'A','B'}),'OFL:Block','Unapproved optimizer block.');
    options = optimoptions('surrogateopt','Display','iter', ...
        'MaxFunctionEvaluations',200,'UseParallel',false, ...
        'UseVectorized',false,'CheckpointFile',checkpoint,'InitialPoints',[0;1]);
end
end
