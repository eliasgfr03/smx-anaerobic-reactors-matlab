function [problem,options] = jwpe_pl_m0_problem(caseConfig,ctx,core,outDir)
%JWPE_PL_M0_PROBLEM Source box/constraints and persisted normalized starts.
% Only native CS has coupled constraints. Diagnostic Kd uses kSigma/Fdir.
problem=struct('name',['CS_M0_' caseConfig.id], ...
    'lbPhysical',caseConfig.lb(:).','ubPhysical',caseConfig.ub(:).', ...
    'parameterNames',string(caseConfig.names(:).'), ...
    'evaluateFcn',@(x)jwpe_pl_m0_eval(x,caseConfig,ctx,core,false), ...
    'recheckFcn',@(x)jwpe_pl_m0_eval(x,caseConfig,ctx,core,true), ...
    'constraintFcnPhysical',[],'initialPointsPhysical',[], ...
    'initialPointsNormalized',caseConfig.initialNormalized, ...
    'objectiveLimit',[],'outputDir',outDir,'isExpensive',true);
if strcmp(caseConfig.map,'anchor')
    problem.constraintFcnPhysical=@(x)jwpe_03b_native_ineq_v1(x,core);
elseif strcmp(caseConfig.map,'native')
    names={'Kd','kb','krev','kG','tinf','Ai'};
    idx=find(strcmp(names,caseConfig.profile));
    problem.constraintFcnPhysical=@(x)jwpe_s04_conditional_ineq_v2( ...
        x,idx,caseConfig.fixedValue,core);
end
options=caseConfig.config;
% Output policy only: no disk forward cache, per-trial files or checkpoint tree.
% Frozen initial normalized coordinates avoid a second normalization roundtrip.
options.checkpointPolicy='never';
end
