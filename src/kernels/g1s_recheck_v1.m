function check = g1s_recheck_v1(selected,repeated,cfg)
check=struct('sameZ',isequal(selected.z,repeated.z), ...
    'sameTheta',isequal(selected.theta,repeated.theta), ...
    'maxPredictionDelta',max(abs(selected.sim.Cout-repeated.sim.Cout)), ...
    'maxStateDelta',max(abs(selected.sim.states-repeated.sim.states),[],'all'), ...
    'NLLDelta',repeated.fit.nll-selected.fit.nll, ...
    'DirectNLLDelta',repeated.fit.directRecalculationDelta-selected.fit.directRecalculationDelta);
check.pass=check.sameZ && check.sameTheta && ...
    check.maxPredictionDelta<=cfg.likelihood.direct_NLL_tolerance && ...
    check.maxStateDelta<=cfg.likelihood.direct_NLL_tolerance && ...
    abs(check.NLLDelta)<=cfg.likelihood.independent_recheck_NLL_tolerance && ...
    abs(check.DirectNLLDelta)<=cfg.likelihood.direct_NLL_tolerance;
end
