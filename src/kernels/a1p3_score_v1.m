function score = a1p3_score_v1(response,prediction,sigmaA,sigmaP)
%A1P3_SCORE_V1 Fixed no-refit predictive score and descriptive metrics.
T=a1p3_schema_v1('canonical',response); prediction=double(prediction(:));
assert(height(T)==17 && numel(prediction)==17 && all(isfinite(prediction)) && ...
    all(prediction>=0) && isscalar(sigmaA) && sigmaA>0 && ...
    isscalar(sigmaP) && sigmaP>0,'JWPE:A1P3:Score','Invalid score inputs.');
residual=T.Cout_ug_L-prediction; sigma=sqrt(sigmaA.^2+(sigmaP.*prediction).^2);
nll=.5*(log(2*pi)+log(sigma.^2)+(residual.^2)./(sigma.^2));
observedRemoval=100*(1-T.Cout_ug_L./T.Cin_ug_L);
predictedRemoval=100*(1-prediction./T.Cin_ug_L);
point=T; point.Prediction_ug_L=prediction; point.Residual_ug_L=residual;
point.AbsoluteError_ug_L=abs(residual); point.SquaredError_ug2_L2=residual.^2;
point.SigmaFixed_ug_L=sigma; point.FixedNLLContribution=nll;
point.ObservedRemoval_pct=observedRemoval; point.PredictedRemoval_pct=predictedRemoval;
metrics=table(T.Reactor(1),height(T),nnz(T.RawZeroMappedToLOD),mean(residual), ...
    mean(abs(residual)),sqrt(mean(residual.^2)),nnz(residual<0),nnz(residual==0), ...
    nnz(residual>0),mean(observedRemoval),median(observedRemoval), ...
    mean(predictedRemoval),median(predictedRemoval),sum(nll),mean(nll), ...
    'VariableNames',{'Reactor','N','MappedZeroCount','Bias_ug_L','MAE_ug_L', ...
    'RMSE_ug_L','ResidualNegativeCount','ResidualZeroCount','ResidualPositiveCount', ...
    'MeanObservedRemoval_pct','MedianObservedRemoval_pct', ...
    'MeanPredictedRemoval_pct','MedianPredictedRemoval_pct', ...
    'FixedHoldoutNLL','MeanFixedHoldoutNLL'});
score=struct('point',point,'metrics',metrics);
end
