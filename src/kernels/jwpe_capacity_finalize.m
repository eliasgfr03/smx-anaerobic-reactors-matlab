function jwpe_capacity_finalize(folder,result)
%JWPE_CAPACITY_FINALIZE Compact completed outputs with an exact manifest.
assert(strcmp(result.status,'TEMPORAL_COMPARISON_COMPLETE') && ...
    result.nObs==33 && result.horizon_d==94 && ~result.phaseIIIAccessed && ...
    height(result.pointwise)==66 && height(result.comparison)==1 && ...
    height(result.activity)==941 && ~result.parameterPooling, ...
    'JWPE:Capacity:Incomplete','Incomplete or inconsistent temporal result.');
summary=struct('status',result.status,'role',result.role,'stage',result.stage, ...
    'reactor',result.reactor,'nObs',33,'horizon_d',94,'phaseIIIAccessed',false, ...
    'rawBudgets',result.rawBudgets,'identity',result.identity, ...
    'reference',result.reference,'scientificPromotion',false,'parameterPooling',false);
names={'result.mat','comparison.csv','pointwise.csv','activity.csv','summary.json'};
values={result,result.comparison,result.pointwise,result.activity,jsonencode(summary)};
kinds={'mat','table','table','table','text'};
for i=1:numel(names)
    assert(~isfile(fullfile(folder,names{i})),'JWPE:Capacity:Overwrite', ...
        'Existing output must remain intact.');
end
for i=1:numel(names); jwpe_run_write(folder,names{i},values{i},kinds{i},false); end
jwpe_capacity_manifest(folder,names);
end
