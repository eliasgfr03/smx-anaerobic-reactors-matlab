function result = jwpe_capacity_assemble(ctx,cases,stage,identity,rawBudgets,reference)
%JWPE_CAPACITY_ASSEMBLE Existing endpoints and source comparison equations.
% Does not integrate a model, evaluate a likelihood or run an optimizer.
% Technical tests use only fabricated concentrations/scores, never real fits.
if nargin<6; reference=struct(); end
core=jwpe_capacity_core_config(); base=jwpe_03b_config_v1(core);
g1=cases.G1.recheck;
assert(g1.valid && numel(g1.prediction_ug_L)==33 && ...
    isequal(g1.observed_ug_L(:),ctx.calibrationObserved_ug_L(:)), ...
    'JWPE:Capacity:Incomplete','G1 endpoint/data mismatch.');
if strcmp(stage,'G1_A1')
    names={'G1','A1'};
    comparison=jwpe_03b_compare_models_v1(g1,cases.A1.recheck,ctx,base);
    t=(0:0.1:94).'; p=JWPE_parameter_struct(jwpe_inf_native_to_engine(g1.thetaNative));
    activity=table(t,JWPE_activity_G1(t,p),ones(size(t)), ...
        'VariableNames',{'Time_d','A_G1','A_A1'});
else
    assert(strcmp(stage,'LOG2'),'JWPE:Capacity:Scope','Unknown comparison stage.');
    names={'G1','LOG2'};
    cfg=jwpe_03b_log2_config_v1(core,base);
    [comparison,activity]=jwpe_03b_log2_compare_v1(g1,cases.LOG2.recheck,ctx,cfg);
end
slots=cell(2,1);
for i=1:2
    fit=cases.(names{i}).recheck;
    assert(fit.valid && numel(fit.prediction_ug_L)==33 && ...
        isequal(fit.observed_ug_L(:),ctx.calibrationObserved_ug_L(:)) && ...
        all(isfinite(fit.prediction_ug_L)) && isfinite(fit.nll), ...
        'JWPE:Capacity:Incomplete','Invalid comparison endpoint.');
    slots{i}=table(repmat(string(names{i}),33,1),ctx.calibrationTimes_d(:), ...
        1+double(ctx.calibrationTimes_d(:)>49), ...
        ctx.dataForcing.Cin_ug_L(:),fit.observed_ug_L(:),fit.prediction_ug_L(:), ...
        fit.observed_ug_L(:)-fit.prediction_ug_L(:), ...
        'VariableNames',{'Model','Time_d','Phase','Cin_ug_L','Observed_ug_L', ...
        'Simulated_ug_L','Residual_ug_L'});
end
fields=fieldnames(rawBudgets);
for i=1:numel(fields)
    b=rawBudgets.(fields{i});
    assert(~b.pending && b.rawFailed==0 && b.rawAttempts<=51, ...
        'JWPE:Public:Budget','Uncertain/failed/exhausted result.');
end
result=struct('status','TEMPORAL_COMPARISON_COMPLETE','role','NEW_RUN', ...
    'stage',stage,'reactor',ctx.reactor,'nObs',33,'horizon_d',94, ...
    'phaseIIIAccessed',false,'model','M0 reversible','cases',cases, ...
    'phaseAudit',ctx.phaseAudit,'harmonization',ctx.harmonization, ...
    'identity',identity,'rawBudgets',rawBudgets,'reference',reference, ...
    'comparison',comparison,'pointwise',vertcat(slots{:}),'activity',activity, ...
    'scientificPromotion',false,'parameterPooling',false);
end
