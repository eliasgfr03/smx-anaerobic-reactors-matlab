function out = tb_like_v1(z,prediction,ctx,cfg)
%TB_LIKE_V1 Evaluate the frozen likelihood and transformed log target.

[physical,transform] = tb_xform_v1('to_physical',z,cfg);
assert(size(physical,1)==1,'JWPE:TB:Target','One state is required.');
assert(tb_support_v1(physical,cfg),'JWPE:TB:Support', ...
    'Within-target state is outside a hard physical support.');
prediction = double(prediction(:));
assert(numel(prediction)==cfg.phase.observationCount && ...
    all(isfinite(prediction)),'JWPE:TB:Target','Invalid persisted prediction.');
[nll,likelihood] = jwpe_inf_observation_loglik(prediction, ...
    ctx.observed_ug_L,cfg.likelihood.model,physical(6:7), ...
    cfg.likelihood.lod);
assert(isfinite(nll) && likelihood.valid,'JWPE:TB:Target', ...
    'Nonfinite within-support likelihood.');
[logPrior,prior] = tb_prior_v1(physical,cfg);
logTarget = -nll+logPrior+transform.logJ;
assert(isfinite(logTarget),'JWPE:TB:Target', ...
    'Nonfinite within-support transformed target.');
out = struct('z',double(z(:).'),'physical',physical,'nll',nll, ...
    'logPriorPhys',logPrior,'logJ',transform.logJ, ...
    'logTarget',logTarget,'likelihood',likelihood,'prior',prior);
end
