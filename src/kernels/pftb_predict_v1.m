function out=pftb_predict_v1(mechanistic,data)
%PFTB_PREDICT_V1 PF adapter: retain the accepted negative-state rejection.
assert(isfield(data,'confirmScience') && isequal(data.confirmScience,true), ...
    'JWPE:Public:ScienceHeld','Scientific calls are held.');
[hit,value,key]=jwpe_mcmc_memory('probe','prediction',mechanistic);
if hit,out=value;out.cacheHit=true;out.rawIncrement=0;return,end
started=tic;sim=m1_pf_sim_v1(data.ctx,mechanistic,m1_cfg_v1());
assert(strcmp(sim.model,'M1') && strcmp(sim.reactor,'PF') && ...
    isequal(sim.times_d(:),data.ctx.auditTimes_d(:)) && max(sim.times_d)==94 && ...
    all(isfinite(sim.Cout_SMX)) && all(isfinite(sim.SMX),'all'), ...
    'JWPE:PFTB:ForwardFailure','Invalid PF forward.');
c=pftb_class_v1('minimum',sim.minSMX,data.cfg);
if c.invalid
 out=struct('valid',false,'classification',c.classification, ...
     'prediction',nan(33,1),'minimum',sim.minSMX,'cacheHit',false, ...
     'rawIncrement',1,'key',key,'elapsed_s',toc(started));return
end
[found,loc]=ismembertol(data.ctx.observationTimes_d,sim.times_d,1e-12,'DataScale',1);
assert(all(found) && numel(loc)==33 && all(loc>0));
out=struct('valid',true,'classification','FINITE_STATE_WITHIN_TOLERANCE', ...
    'prediction',double(sim.Cout_SMX(loc)),'minimum',sim.minSMX, ...
    'cacheHit',false,'rawIncrement',1,'key',key,'elapsed_s',toc(started));
jwpe_mcmc_memory('put','prediction',mechanistic,out);
end
