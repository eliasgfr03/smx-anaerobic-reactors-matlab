function result = jwpe_oem_assemble(inputs,modelRuns,rawBudget)
%JWPE_OEM_ASSEMBLE Source ICs/diagnostics for already computed endpoints.
%   No model, likelihood or optimizer call. Synthetic QA must use fake data.
cfg = inputs.cfg;
assert(numel(modelRuns)==3 && ~rawBudget.pending && ...
    rawBudget.rawAttempts<=cfg.public.rawForwardHardMax, ...
    'JWPE:OEM:Incomplete','Incomplete model set or uncertain raw attempt.');
comparisonRows = cell(3,28);
startRows = cell(12,26);
pointTables = cell(3,1);
phaseTables = cell(3,1);
cases = struct();
context = struct('reactor',inputs.reactor,'data',inputs.data);
for im=1:3
    modelName = cfg.modelNames{im};
    runs = modelRuns{im};
    pick = jwpe_oem_choose(runs,cfg);
    best = pick.best;
    assert(strcmp(best.modelName,modelName) && ...
        strcmp(best.reactor,inputs.reactor),'JWPE:OEM:Identity', ...
        'Endpoint model/reactor identity mismatch.');
    spec = JWPE_OEM_model_spec_v1_3(modelName,cfg);
    diagnostics = JWPE_OEM_diagnostics_v1_3(context,best,cfg);
    n = inputs.nObs;
    k = spec.nEstimated;
    AIC = 2*k-2*best.logLik;
    if n-k-1>0
        AICc = AIC+2*k*(k+1)/(n-k-1);
    else
        AICc = Inf;
    end
    BIC = k*log(n)-2*best.logLik;
    [sigmaA,sigmaP] = local_sigmas(modelName,best.errorPars);
    comparisonRows(im,:) = {inputs.reactor,modelName,best.qualityPass, ...
        pick.stability,best.nll,best.logLik,k,n,AIC,AICc,BIC,NaN,NaN, ...
        inputs.nCensored,best.theta(1),best.theta(2),best.theta(3), ...
        best.theta(4),best.theta(5),best.theta(6),sigmaA,sigmaP, ...
        pick.bestIndex,pick.agreeingStarts,best.qualityStatus, ...
        local_collapse(spec,best),best.firstOrderOptimality,best.exitflag};
    for is=1:4
        r = runs(is);
        [sa,sp] = local_sigmas(modelName,r.errorPars);
        startRows((im-1)*4+is,:) = {inputs.reactor,modelName,is, ...
            r.nll,r.nllRecheck,r.recheckDeltaNLL,r.qualityPass,r.qualityStatus, ...
            r.exitflag,r.firstOrderOptimality,r.theta(1),r.theta(2),r.theta(3), ...
            r.theta(4),r.theta(5),r.theta(6),sa,sp, ...
            r.search.functionCount,r.polish.functionCount, ...
            r.rawForwardCallsOptimization,r.rawForwardCallsIndependentRecheck, ...
            r.cache.hits,r.elapsed_s,r.search.nll,r.searchToPolishDeltaNLL};
    end
    pt = diagnostics.pointTable;
    pt.Model = repmat(string(modelName),height(pt),1);
    pointTables{im} = pt;
    phaseTables{im} = diagnostics.phaseTable;
    cases.(modelName) = struct('best',best,'runs',runs, ...
        'bestIndex',pick.bestIndex,'stability',pick.stability, ...
        'agreeingStarts',pick.agreeingStarts,'diagnostics',diagnostics, ...
        'informationCriteria',struct('n',n,'k',k,'AIC',AIC,'AICc',AICc,'BIC',BIC));
end
comparison = cell2table(comparisonRows,'VariableNames', ...
    {'Reactor','Model','ValidForICComparison','MultistartStability', ...
    'NLL','LogLik','K','N','AIC','AICc','BIC','DeltaAICc','DeltaBIC', ...
    'NCensored','Kd','kb','krev','kG','tinf','Ai','sigmaA','sigmaP', ...
    'BestStart','AgreeingStarts','QualityStatus','ComponentCollapse', ...
    'FirstOrderOptimality','Exitflag'});
valid = comparison.ValidForICComparison & isfinite(comparison.AICc) & ...
    isfinite(comparison.BIC);
if any(valid)
    comparison.DeltaAICc(valid) = comparison.AICc(valid)-min(comparison.AICc(valid));
    comparison.DeltaBIC(valid) = comparison.BIC(valid)-min(comparison.BIC(valid));
end
starts = cell2table(startRows,'VariableNames', ...
    {'Reactor','Model','Start','NLL','RecheckNLL','RecheckDelta', ...
    'QualityPass','QualityStatus','Exitflag','FirstOrderOptimality', ...
    'Kd','kb','krev','kG','tinf','Ai','sigmaA','sigmaP', ...
    'SearchFunctionCount','PolishFunctionCount','RawOptimizationForwards', ...
    'RawRecheckForwards','CacheHits','Elapsed_s','SearchNLL','SearchToPolishDeltaNLL'});
result = struct('status','HISTORICAL_OEM_COMPLETE_REVIEW_REQUIRED', ...
    'role',inputs.role,'reactor',inputs.reactor,'cfg',cfg, ...
    'identity',inputs.identity,'nObs',inputs.nObs,'nCensored',inputs.nCensored, ...
    'horizon_d',145,'phaseIIIUsedOnlyForHistoricalOEM',true, ...
    'scientificPromotion',false,'nativeFminconResume',false, ...
    'rawBudget',rawBudget,'cases',cases,'comparison',comparison, ...
    'starts',starts,'pointwise',vertcat(pointTables{:}), ...
    'phases',vertcat(phaseTables{:}));
end

function [sigmaA,sigmaP] = local_sigmas(modelName,errorPars)
sigmaA = NaN;
sigmaP = NaN;
switch modelName
    case 'additive'
        sigmaA = errorPars(1);
    case 'proportional'
        sigmaP = errorPars(1);
    case 'combined'
        sigmaA = errorPars(1);
        sigmaP = errorPars(2);
end
end

function text = local_collapse(spec,run)
if isempty(run.errorComponentCollapsed) || ~any(run.errorComponentCollapsed)
    text = 'none';
else
    text = strjoin(spec.errorNames(logical(run.errorComponentCollapsed)),'+');
end
end
