function [selected,receipt] = ppu_select_v1(reactor,chains,cfg)
%PPU_SELECT_V1 Select one complete row from every frozen chain-position stratum.

reactor=upper(string(reactor)); rcfg=cfg.(char(reactor));
caller=rng; cleanup=onCleanup(@()rng(caller));
stream=RandStream('mt19937ar','Seed',rcfg.selectionSeed); initial=stream.State;
n=cfg.drawsPerReactor; Reactor=repmat(reactor,n,1); ChainID=zeros(n,1);
RowID=zeros(n,1); StratumID=zeros(n,1); StratumLower=zeros(n,1);
StratumUpper=zeros(n,1); SourceSHA256=strings(n,1); X=zeros(n,7); k=0;
for c=1:cfg.chains
    for s=1:cfg.strataPerChain
        k=k+1; lo=(s-1)*rcfg.stratumWidth+1; hi=s*rcfg.stratumWidth;
        row=lo+randi(stream,hi-lo+1)-1;
        ChainID(k)=c; RowID(k)=row; StratumID(k)=s;
        StratumLower(k)=lo; StratumUpper(k)=hi;
        SourceSHA256(k)=cfg.traceHashes.(char(reactor))(c); X(k,:)=chains{c}(row,:);
    end
end
assert(k==n && numel(unique(ChainID*100000+RowID))==n, ...
    'JWPE:PPU:Selection','Selection count or uniqueness failed.');
assert(all(X>=rcfg.supportLower & X<=rcfg.supportUpper,'all'), ...
    'JWPE:PPU:Support','Selected row is outside frozen support.');
selected=table(Reactor,ChainID,RowID,StratumID,StratumLower,StratumUpper, ...
    SourceSHA256,X(:,1),X(:,2),X(:,3),X(:,4),X(:,5),X(:,6),X(:,7), ...
    'VariableNames',{'Reactor','ChainID','RowID','StratumID', ...
    'StratumLower','StratumUpper','SourceSHA256','Kd','kb','kG','tinf', ...
    'Ai','sigmaA','sigmaP'});
receipt=struct('protocolID',cfg.protocolID,'reactor',char(reactor), ...
    'algorithm','MT19937AR_LOCAL_EQUAL_CHAIN_POSITION_STRATA', ...
    'seed',rcfg.selectionSeed,'derivationDigest',rcfg.selectionDigest, ...
    'initialState',initial,'finalState',stream.State,'drawCount',n, ...
    'strataPerChain',cfg.strataPerChain,'stratumWidth',rcfg.stratumWidth, ...
    'globalRNGUnchanged',isequal(caller,rng));
assert(receipt.globalRNGUnchanged,'JWPE:PPU:RNG','Selection changed global RNG.');
initialHash=string(ppu_io_v1('hash',typecast(uint32(initial(:)),'uint8'),'bytes'));
finalState=stream.State;
finalHash=string(ppu_io_v1('hash',typecast(uint32(finalState(:)),'uint8'),'bytes'));
selected=addvars(selected,repmat(rcfg.selectionSeed,n,1), ...
    repmat(initialHash,n,1),repmat(finalHash,n,1),'After','SourceSHA256', ...
    'NewVariableNames',{'SelectionSeed','SelectionInitialStateSHA256', ...
    'SelectionFinalStateSHA256'});
clear cleanup
end
