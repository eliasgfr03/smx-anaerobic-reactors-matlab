function state = jwpe_calibration_record(action,state,value)
%JWPE_CALIBRATION_RECORD Pure budget, cache and trace state transitions.
%   This helper does not generate a prediction or evaluate a likelihood.
%   attempt cannot be retried automatically or resumed as a fresh run.
action = lower(string(action));
switch action
    case "begin"
        assert(isempty(state.pending) && state.failures==0, ...
            'JWPE:Public:State','A failed or uncertain attempt remains.');
        assert(isequal(size(value.theta),[1,5]) && ...
            value.theta(1)==state.cfg.fixedKd && ...
            all(value.theta>=state.cfg.lower) && ...
            all(value.theta<=state.cfg.upper) && ...
            strcmp(value.key,jwpe_calibration_key(value.theta)), ...
            'JWPE:Public:State','Attempt identity/support mismatch.');
        if strcmp(value.phase,'OPT')
            assert(~state.searchFinished && ...
                state.optimizerCalls<state.cfg.budget.optimizerCalls, ...
                'JWPE:Public:Budget','Optimizer-call budget exhausted.');
            state.optimizerCalls = state.optimizerCalls+1;
        else
            assert(strcmp(value.phase,'RECHECK') && state.searchFinished ...
                && state.rechecks==0 && ~value.cacheHit && ...
                ~isempty(state.best) && isequal(value.theta,state.best.theta), ...
                'JWPE:Public:Recheck','Invalid independent recheck.');
            state.rechecks = state.rechecks+1;
        end
        if value.cacheHit
            state.cacheHits = state.cacheHits+1;
        else
            assert(state.rawForwards<state.cfg.budget.rawForwards, ...
                'JWPE:Public:Budget','Raw-forward budget exhausted.');
            state.rawForwards = state.rawForwards+1;
        end
        state.pending = value;
        state.status = 'EVALUATING';
    case "complete"
        assert(~isempty(state.pending) && ...
            isequal(value.theta,state.pending.theta) && ...
            strcmp(value.key,state.pending.key), ...
            'JWPE:Public:State','Completion does not match the pending attempt.');
        request = state.pending;
        if value.eligible
            assert(isfinite(value.nll), ...
                'JWPE:Public:State','Eligible completion must have finite NLL.');
            if strcmp(request.phase,'OPT')
                if isempty(state.best) || value.nll<state.best.nll
                    state.best = value;
                end
                if ~request.cacheHit
                    assert(~any(state.cacheKeys==string(value.key)), ...
                        'JWPE:Public:Cache','Duplicate uncached completion.');
                    state.cacheKeys(end+1,1) = string(value.key);
                    state.cache{end+1,1} = value;
                end
            else
                assert(abs(value.nll-state.best.nll)<= ...
                    state.cfg.recheckToleranceNLL, ...
                    'JWPE:Public:Recheck','Independent NLL recheck disagrees.');
                state.recheck = value;
            end
        else
            assert(strcmp(state.cfg.reactor,'PF') && ...
                strcmp(request.phase,'OPT') && ~request.cacheHit && ...
                strcmp(value.classification,'COMPLETE_INVALID_NEGATIVE_STATE') ...
                && isnan(value.nll), ...
                'JWPE:Public:State','Unapproved invalid evaluation.');
            state.invalidEvaluations = state.invalidEvaluations+1;
        end
        row = struct('Phase',string(request.phase),'Eligible',value.eligible, ...
            'NLL',value.nll,'RawForward',double(~request.cacheHit), ...
            'CacheHit',request.cacheHit,'Kd',value.theta(1), ...
            'kb',value.theta(2),'kG',value.theta(3),'tinf',value.theta(4), ...
            'Ai',value.theta(5),'SigmaA',value.sigmaA,'SigmaP',value.sigmaP, ...
            'MinSMX',value.minSMX,'Classification',string(value.classification));
        state.trace(end+1,1) = row;
        state.pending = struct([]);
        state.status = 'RUNNING';
        state.rngCurrent = rng;
    case "search_complete"
        assert(isempty(state.pending) && state.failures==0 && ...
            ~isempty(state.best) && state.optimizerCalls<= ...
            state.cfg.budget.optimizerCalls && ~state.searchFinished, ...
            'JWPE:Public:State','No valid completed search to finalize.');
        rows = state.trace(string({state.trace.Phase})=="OPT");
        assert(numel(rows)==state.optimizerCalls && ...
            nnz([rows.Eligible])+state.invalidEvaluations==numel(rows) && ...
            min([rows([rows.Eligible]).NLL])==state.best.nll, ...
            'JWPE:Public:State','Search counters or lower endpoint disagree.');
        state.optimizer = value;
        state.searchFinished = true;
        state.status = 'SEARCH_COMPLETE';
        state.rngCurrent = rng;
    case "fail"
        state.failures = state.failures+1;
        state.status = 'FAILED_REVIEW_REQUIRED';
        state.failure = value;
        state.rngCurrent = rng;
    otherwise
        error('JWPE:Public:State','Unknown record action: %s',action);
end
end
