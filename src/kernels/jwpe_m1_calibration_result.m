function result = jwpe_m1_calibration_result(state)
%JWPE_M1_CALIBRATION_RESULT Assemble a completed result; no scientific calls.
%   The result records the independently checked endpoint, not a global
assert(state.searchFinished && isempty(state.pending) && state.failures==0 ...
    && state.rechecks==1 && ~isempty(state.best) && ~isempty(state.recheck) ...
    && isequal(state.best.theta,state.recheck.theta) && ...
    state.rawForwards<=state.cfg.budget.rawForwards && ...
    state.optimizerCalls<=state.cfg.budget.optimizerCalls, ...
    'JWPE:Public:State','Result is incomplete or outside its budget.');
delta = state.recheck.nll-state.best.nll;
assert(abs(delta)<=state.cfg.recheckToleranceNLL, ...
    'JWPE:Public:Recheck','Independent recheck disagreement.');
result = struct('status','CALIBRATION_COMPLETE_REVIEW_REQUIRED', ...
    'reactor',state.cfg.reactor,'model',state.cfg.model, ...
    'parameterNames',state.cfg.parameterNames,'parameterUnits', ...
    state.cfg.parameterUnits,'theta',state.best.theta, ...
    'nll',state.best.nll,'recheckNLL',state.recheck.nll, ...
    'recheckDelta',delta,'sigmaA',state.recheck.sigmaA, ...
    'sigmaP',state.recheck.sigmaP,'errorFit',state.recheck.errorFit, ...
    'prediction_ug_L',state.recheck.prediction_ug_L, ...
    'observationTimes_d',state.context.observationTimes_d, ...
    'observed_ug_L',state.context.observed_ug_L, ...
    'phaseI',state.context.observationPhaseI, ...
    'phaseII',state.context.observationPhaseII, ...
    'auditTimes_d',state.context.auditTimes_d, ...
    'auditCout_ug_L',state.recheck.auditCout_ug_L, ...
    'nllPhaseI',state.recheck.nllPhaseI, ...
    'nllPhaseII',state.recheck.nllPhaseII, ...
    'classification',state.recheck.classification, ...
    'optimizerCalls',state.optimizerCalls,'rawForwards',state.rawForwards, ...
    'cacheHits',state.cacheHits,'invalidEvaluations',state.invalidEvaluations, ...
    'failures',state.failures,'retries',0,'phaseIIIExcluded',true, ...
    'horizon_d',94,'cfg',state.cfg,'identity',state.identity, ...
    'rngInitial',state.rngInitial,'rngFinal',state.rngCurrent, ...
    'optimizer',state.optimizer,'trace',struct2table(state.trace));
result.testOnly=state.cfg.testOnly;
result.productionCertified=false;
if state.cfg.testOnly,result.status='DEMO_CALIBRATION_COMPLETE';end
end
