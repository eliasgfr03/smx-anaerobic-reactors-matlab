function data = jwpe_interface_tables_v1(spec,paths)
%JWPE_INTERFACE_TABLES_V1 Validate tables without solver, RNG or response scoring.
data=struct();
if ~isfield(paths,'forcing'),return;end
F=readtable(paths.forcing,'VariableNamingRule','preserve','TextType','string');
assert(isequal(F.Properties.VariableNames,{'Reactor','Time_d','Cin_ug_L'}), ...
    'JWPE:Interface:Forcing','Forcing must contain only Reactor,Time_d,Cin_ug_L.');
assert(height(F)>0 && all(string(F.Reactor)==string(spec.reactorID)) && ...
    all(isfinite(F.Time_d)) && all(diff(F.Time_d)>0) && ...
    all(isfinite(F.Cin_ug_L)) && all(F.Cin_ug_L>=0), ...
    'JWPE:Interface:Forcing','Invalid forcing order/reactor/values.');
P=readtable(paths.phases,'VariableNamingRule','preserve','TextType','string');
assert(isequal(P.Properties.VariableNames,{'Reactor','Phase','Start_d','End_d','Use'}), ...
    'JWPE:Interface:Phases','Phase schema mismatch.');
assert(height(P)>0 && all(string(P.Reactor)==string(spec.reactorID)) && ...
    all(isfinite(P.Start_d)) && all(isfinite(P.End_d)) && ...
    all(P.End_d>P.Start_d) && numel(unique(P.Phase))==height(P) && ...
    all(ismember(P.Use,["calibration","holdout"])), ...
    'JWPE:Interface:Phases','Invalid phase intervals or labels.');
assert(all(P.Start_d(2:end)==P.End_d(1:end-1)), ...
    'JWPE:Interface:Phases','Require ordered contiguous explicit phase intervals.');
data.forcing=F;data.phases=P;
if isfield(paths,'observations')
    O=readtable(paths.observations,'VariableNamingRule','preserve','TextType','string');
    expected={'Reactor','Time_d','Phase','Cout_ug_L','CensorFlag','LOD_ug_L'};
    assert(isequal(O.Properties.VariableNames,expected) && height(O)>0, ...
        'JWPE:Interface:Observations','Observation schema mismatch.');
    assert(all(string(O.Reactor)==string(spec.reactorID)) && ...
        all(isfinite(O.Time_d)) && all(diff(O.Time_d)>0) && ...
        all(isfinite(O.Cout_ug_L)) && all(O.Cout_ug_L>=0) && ...
        all(isfinite(O.LOD_ug_L)) && all(O.LOD_ug_L>0), ...
        'JWPE:Interface:Observations','Invalid observed values/order/reactor.');
    raw=lower(string(O.CensorFlag));
    assert(all(ismember(raw,["0","1","false","true"])), ...
        'JWPE:Interface:Censor','CensorFlag must be boolean or 0/1.');
    O.CensorFlag=ismember(raw,["1","true"]);
    for i=1:height(O)
        % Right-closed intervals: first includes t0, subsequent exclude start.
        row=find(O.Time_d(i)<=P.End_d & ...
            (O.Time_d(i)>P.Start_d | ((1:height(P)).'==1 & O.Time_d(i)==P.Start_d)));
        assert(isscalar(row) && O.Phase(i)==P.Phase(row), ...
            'JWPE:Interface:Phases','Observation phase/time mismatch.');
    end
    data.observations=O;
end
end
