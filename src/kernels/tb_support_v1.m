function inside = tb_support_v1(physical,cfg)
%TB_SUPPORT_V1 Test frozen closed physical supports.

physical = double(physical(:).');
inside = numel(physical)==7 && all(isfinite(physical)) && ...
    all(physical>=cfg.support.lowerPhysical) && ...
    all(physical<=cfg.support.upperPhysical) && ...
    physical(3)>cfg.support.lowerPhysical(3) && ...
    physical(3)<cfg.support.upperPhysical(3) && physical(5)>0 && ...
    physical(5)<1;
end
