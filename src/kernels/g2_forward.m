function out = g2_forward(ctx,thetaNative,cfg)
%G2_FORWARD Execute one guarded native forward at exactly 18 Phase-I-II times.

thetaNative = double(thetaNative(:).');
assert(numel(thetaNative)==6 && all(isfinite(thetaNative)), ...
    'JWPE:G2:Mapping','Expected finite [Kd,kb,krev,kG,tinf,Ai].');
assert(thetaNative(2)>=0 && thetaNative(3)>=0 && ...
    thetaNative(2)+thetaNative(3)>0,'JWPE:G2:Mapping', ...
    'Invalid native reversible-rate coordinates.');
assert(isequal(ctx.outputTimes_d,cfg.times.all_d(:)) && ...
    isequal(cfg.times.all_d,5:5:90) && numel(ctx.outputTimes_d)==18 && ...
    ~any(ctx.outputTimes_d>90),'JWPE:G2:OutputTimes', ...
    'Forward output-time guard failed.');
assert(all(isnan(ctx.forcingData.Cout_ug_L)),'JWPE:G2:Leakage', ...
    'Response values are present in forcing.');
[thetaEngine,derived] = jwpe_inf_native_to_engine(thetaNative);
back = jwpe_inf_engine_to_native(thetaEngine);
assert(all(abs(back-thetaNative)<=32*eps(max(1,abs(thetaNative)))), ...
    'JWPE:G2:Mapping','Native/engine round-trip failed.');

result = ctx.engine(thetaEngine,ctx.forcingData,ctx.settings,ctx.outputTimes_d,false);
assert(isstruct(result) && isfield(result,'prediction_ug_L') && ...
    isfield(result,'target_times'),'JWPE:G2:ForwardFailure', ...
    'Forward returned an incomplete structure.');
times = double(result.target_times(:));
y = double(result.prediction_ug_L(:));
assert(isequal(times,ctx.outputTimes_d) && numel(y)==18, ...
    'JWPE:G2:Dimension','Forward returned an invalid output grid.');
assert(all(isfinite(y)),'JWPE:G2:ForwardFailure','Forward returned NaN or Inf.');
out = struct('prediction_ug_L',y,'times_d',times,'state','OK', ...
    'thetaNative',thetaNative,'thetaEngine',thetaEngine,'derived',derived);
end
