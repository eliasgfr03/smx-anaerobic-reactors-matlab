function state = jwpe_m1_calibration_state(inputs)
%JWPE_M1_CALIBRATION_STATE Construct the production state without evaluation.
%   All cached predictions and trace records belong to this run. No solver
%   state arrays or historical checkpoints are imported.
cfg = inputs.cfg;
assert(cfg.fixedKd==0.020 && isequal(cfg.freeIndices,2:5) && ...
    cfg.lower(1)==cfg.fixedKd && cfg.upper(1)==cfg.fixedKd && ...
    ((~cfg.testOnly && cfg.budget.optimizerCalls==250 && cfg.budget.rawForwards==251) || ...
    (cfg.testOnly && cfg.budget.optimizerCalls==24 && cfg.budget.rawForwards==25)) && ...
    cfg.budget.recheck==1 && cfg.budget.retries==0, ...
    'JWPE:Public:Config','Changed fixed-Kd calibration policy.');
state = struct('cfg',cfg,'context',inputs.context, ...
    'initialPoints',inputs.initialPoints,'identity',inputs.identity, ...
    'status','CREATED','optimizerCalls',0,'rawForwards',0, ...
    'cacheHits',0,'rechecks',0,'failures',0,'invalidEvaluations',0, ...
    'pending',struct([]),'searchFinished',false,'best',struct([]), ...
    'recheck',struct([]),'cacheKeys',strings(0,1),'cache',{cell(0,1)}, ...
    'trace',struct('Phase',{},'Eligible',{},'NLL',{},'RawForward',{}, ...
    'CacheHit',{},'Kd',{},'kb',{},'kG',{},'tinf',{},'Ai',{}, ...
    'SigmaA',{},'SigmaP',{},'MinSMX',{},'Classification',{}), ...
    'optimizer',struct(), ...
    'rngInitial',struct(),'rngCurrent',struct(),'runDirectory','');
end
