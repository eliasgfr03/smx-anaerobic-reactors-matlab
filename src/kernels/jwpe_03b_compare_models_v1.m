function comparison = jwpe_03b_compare_models_v1(g1,a1,ctx,cfgStage)
%JWPE_03B_COMPARE_MODELS_V1 Formal G1 vs A(t)=1 comparison on Phases I-II.
%
% Delta fields are defined as A1 - G1. Positive DeltaNLL/DeltaAICc/DeltaBIC
% therefore favor the adaptive G1 model.

assert(g1.valid && a1.valid,'Both model rechecks must be valid.');
n = ctx.nCalibrationObs;
kG1 = cfgStage.informationCriteria.nMeanParametersG1 + ...
    cfgStage.informationCriteria.nErrorParameters;
kA1 = cfgStage.informationCriteria.nMeanParametersA1 + ...
    cfgStage.informationCriteria.nErrorParameters;

icG1 = local_ic(g1.nll,n,kG1);
icA1 = local_ic(a1.nll,n,kA1);

comparison = table( ...
    string(ctx.reactor),n,kG1,kA1,g1.nll,a1.nll,a1.nll-g1.nll, ...
    icG1.AIC,icA1.AIC,icA1.AIC-icG1.AIC, ...
    icG1.AICc,icA1.AICc,icA1.AICc-icG1.AICc, ...
    icG1.BIC,icA1.BIC,icA1.BIC-icG1.BIC, ...
    g1.SSE_zero_as_number,a1.SSE_zero_as_number, ...
    a1.SSE_zero_as_number-g1.SSE_zero_as_number, ...
    g1.RMSE,a1.RMSE,g1.NRMSE,a1.NRMSE,g1.NSE,a1.NSE,g1.bias,a1.bias, ...
    'VariableNames',{'Reactor','Ncal','k_G1_total','k_A1_total', ...
    'NLL_G1','NLL_A1','DeltaNLL_A1_minus_G1', ...
    'AIC_G1','AIC_A1','DeltaAIC_A1_minus_G1', ...
    'AICc_G1','AICc_A1','DeltaAICc_A1_minus_G1', ...
    'BIC_G1','BIC_A1','DeltaBIC_A1_minus_G1', ...
    'SSE_G1','SSE_A1','DeltaSSE_A1_minus_G1', ...
    'RMSE_G1','RMSE_A1','NRMSE_G1','NRMSE_A1','NSE_G1','NSE_A1', ...
    'Bias_G1','Bias_A1'});
end

function ic = local_ic(nll,n,k)
ic.AIC = 2*k + 2*nll;
den = n-k-1;
assert(den>0,'AICc undefined because n-k-1 <= 0.');
ic.AICc = ic.AIC + 2*k*(k+1)/den;
ic.BIC = log(n)*k + 2*nll;
end
