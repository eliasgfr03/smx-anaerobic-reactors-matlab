function info = pf_min_v2(sim,epsFactor)
%PF_MIN_V2 Locate the exact global internal PF minimum without a forward.

if nargin<2, epsFactor = 64; end
assert(isstruct(sim) && isfield(sim,'segments') && ...
    isfield(sim,'minSMX') && isfinite(sim.minSMX) && ...
    isfinite(epsFactor) && epsFactor>=1,'JWPE:PFAP2:Minimum', ...
    'Invalid PF minimum-location input.');
best = Inf; segmentIndex = NaN; phase = NaN;
time_d = NaN; nodeIndex = NaN; solver = '';
for k = 1:numel(sim.segments)
    segment = sim.segments(k);
    assert(isfield(segment,'sol') && isstruct(segment.sol) && ...
        isfield(segment.sol,'y') && isfield(segment.sol,'x') && ...
        all(isfinite(segment.sol.y),'all') && ...
        all(isfinite(segment.sol.x),'all'), ...
        'JWPE:PFAP2:Minimum','Nonfinite or incomplete PF segment.');
    [value,linearIndex] = min(segment.sol.y(:));
    if value<best
        [node,column] = ind2sub(size(segment.sol.y),linearIndex);
        best = value; segmentIndex = k; phase = segment.phase;
        time_d = segment.sol.x(column); nodeIndex = node;
        if isfield(segment.sol,'solver'), solver = char(segment.sol.solver); end
    end
end
scale = max([1,abs(best),abs(sim.minSMX)]);
agreementTolerance = epsFactor*eps(scale);
assert(isfinite(best) && abs(best-sim.minSMX)<=agreementTolerance, ...
    'JWPE:PFAP2:Minimum','Computed segment minimum disagrees with sim.minSMX.');
info = struct('minimum',best,'segmentIndex',segmentIndex, ...
    'phase',phase,'time_d',time_d,'nodeIndex',nodeIndex, ...
    'solver',solver,'reportedMinimum',sim.minSMX, ...
    'agreementDelta',best-sim.minSMX, ...
    'agreementTolerance',agreementTolerance);
end
