function grid = ppu_grid_v1(ctx,cfg)
%PPU_GRID_V1 Validate the accepted Phase-I-II-safe audit grid and forcing.

times=double(ctx.auditTimes_d(:)); regular=(0:0.5:94).';
assert(times(1)==0 && times(end)==cfg.horizon_d && ...
    all(ismember(regular,times)) && all(ismember(ctx.observationTimes_d,times)) && ...
    any(times==49) && ~any(times>94) && numel(ctx.observationTimes_d)==33 && ...
    all(ctx.observationPhaseI | ctx.observationPhaseII) && ...
    ~any(ctx.observationPhaseI & ctx.observationPhaseII) && ...
    ctx.phaseAudit.responseLeakage==false && ctx.phaseAudit.forcingEnd_d==94, ...
    'JWPE:PPU:Grid','Phase-I-II audit grid or forcing guard failed.');
forcingTimes=double(ctx.forcingData.Time_d(:)); forcingCin=double(ctx.forcingData.Cin_ug_L(:));
assert(~any(forcingTimes>94) && all(isnan(ctx.forcingData.Cout_ug_L)), ...
    'JWPE:PPU:Leakage','Phase-III or response leakage in forcing context.');
grid=struct('times_d',times,'regular_d',regular,'forcingTimes_d',forcingTimes, ...
    'forcingCin_ug_L',forcingCin,'observationTimes_d',ctx.observationTimes_d, ...
    'observed_ug_L',ctx.observed_ug_L,'phaseI',ctx.observationPhaseI, ...
    'phaseII',ctx.observationPhaseII,'phaseIIICount',0,'horizon_d',94, ...
    'harmonization',ctx.harmonization);
end
