function [summary,activity] = jwpe_03b_log2_compare_v1(g1,log2,ctx,cfgStage)
%
% Delta values are LOG2 minus G1; negative IC deltas favor LOG2.

n=ctx.nCalibrationObs;
kG1=cfgStage.informationCriteria.nMeanParametersG1 + ...
    cfgStage.informationCriteria.nErrorParameters;
kL=cfgStage.informationCriteria.nMeanParametersLOG2 + ...
    cfgStage.informationCriteria.nErrorParameters;
[aicG,aiccG,bicG]=local_ic(g1.nll,n,kG1);
[aicL,aiccL,bicL]=local_ic(log2.nll,n,kL);

summary=table(string(ctx.reactor),n,kG1,kL,g1.nll,log2.nll, ...
    log2.nll-g1.nll,g1.SSE_zero_as_number,log2.SSE_zero_as_number, ...
    g1.RMSE,log2.RMSE,100*g1.NRMSE,100*log2.NRMSE,g1.NSE,log2.NSE, ...
    aicG,aicL,aicL-aicG,aiccG,aiccL,aiccL-aiccG,bicG,bicL,bicL-bicG, ...
    'VariableNames',{'Reactor','N','k_G1','k_LOG2','NLL_G1','NLL_LOG2', ...
    'DeltaNLL_LOG2_minus_G1','SSE_G1','SSE_LOG2','RMSE_G1','RMSE_LOG2', ...
    'NRMSEpct_G1','NRMSEpct_LOG2','NSE_G1','NSE_LOG2','AIC_G1','AIC_LOG2', ...
    'DeltaAIC_LOG2_minus_G1','AICc_G1','AICc_LOG2','DeltaAICc_LOG2_minus_G1', ...
    'BIC_G1','BIC_LOG2','DeltaBIC_LOG2_minus_G1'});

t=(0:cfgStage.activityGridStep_d:94).';
p=JWPE_parameter_struct(jwpe_inf_native_to_engine(g1.thetaNative));
Ag=JWPE_activity_G1(t,p); Al=jwpe_03b_log2_activity_v1(t,log2.kA,log2.t50);
activity=table(t,Ag(:),Al(:),Al(:)-Ag(:), ...
    'VariableNames',{'Time_d','A_G1','A_LOG2','LOG2_minus_G1'});
end

function [aic,aicc,bic]=local_ic(nll,n,k)
aic=2*k+2*nll;
assert(n-k-1>0,'AICc undefined: n-k-1 <= 0.');
aicc=aic+2*k*(k+1)/(n-k-1);
bic=k*log(n)+2*nll;
end
