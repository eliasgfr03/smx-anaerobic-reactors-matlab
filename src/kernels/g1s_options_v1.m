function options = g1s_options_v1(kind,reactor,cfg,checkpoint)
%G1S_OPTIONS_V1 Construct approved optimizer options without invocation.
kind=upper(string(kind)); reactor=char(upper(string(reactor)));
if kind=="GLOBAL"
    options=optimoptions('surrogateopt','Display','iter', ...
        'MaxFunctionEvaluations',100,'UseParallel',false, ...
        'UseVectorized',false,'CheckpointFile',checkpoint);
    if strcmp(reactor,'CS')
        options.InitialPoints=g1s_map_v1('encode', ...
            cfg.optimizer.CS_initial_point_physical,'CS',cfg);
    else
        assert(isempty(cfg.optimizer.PF_initial_points),'G1S:Config','PF InitialPoints must be empty.');
    end
elseif kind=="LOCAL"
    L=cfg.optimizer.local_options;
    options=optimoptions('patternsearch','Display','iter','Algorithm','classic', ...
        'PollMethod',L.PollMethod,'UseCompletePoll',logical(L.UseCompletePoll), ...
        'ScaleMesh',logical(L.ScaleMesh),'InitialMeshSize',L.InitialMeshSize, ...
        'MaxMeshSize',L.MaxMeshSize,'MeshExpansionFactor',L.MeshExpansionFactor, ...
        'MeshContractionFactor',L.MeshContractionFactor,'MeshTolerance',L.MeshTolerance, ...
        'SearchFcn',[],'UseParallel',false,'UseVectorized',false, ...
        'MaxFunctionEvaluations',60);
else
    error('G1S:Options','Unknown optimizer block.');
end
end
