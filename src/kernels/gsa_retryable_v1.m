function tf = gsa_retryable_v1(identifier,message)
%GSA_RETRYABLE_V1 Classify only unexpected run/solver/output failures for retry.

id = string(identifier); msg = lower(string(message));
nonRetryTokens = ["Config","Phase","Mapping","Budget","Dimension", ...
    "Horizon","Authorization","Dependency","Path","OutputTimes", ...
    "Leakage","Overwrite","Resume","Preflight","Checkcode"];
tf = true;
for token = nonRetryTokens
    if contains(id,token); tf=false; return; end
end
if contains(id,"MATLAB:UndefinedFunction") || contains(msg,"undefined function") || ...
        contains(msg,"not found") || contains(msg,"shadow") || ...
        contains(msg,"missing dependency") || contains(id,"MATLAB:assertion:failed") || ...
        contains(id,"MATLAB:nonExistentField") || contains(id,"MATLAB:badsubscript") || ...
        contains(id,"MATLAB:dimagree") || contains(id,"MATLAB:minrhs") || ...
        contains(id,"MATLAB:maxrhs") || contains(id,"MATLAB:TooManyInputs")
    tf=false;
end
end
