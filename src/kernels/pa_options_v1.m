function options = pa_options_v1(kind,cfg,checkpoint)
%PA_OPTIONS_V1 Exact approved option constructors; invokes no optimizer.
kind=upper(string(kind));
if ismember(kind,["A","B"])
    options=optimoptions('surrogateopt','Display','iter', ...
        'MaxFunctionEvaluations',200,'UseParallel',false, ...
        'UseVectorized',false,'CheckpointFile',checkpoint, ...
        'InitialPoints',[0;1]);
elseif kind=="LOCAL"
    L=cfg.optimizer.local_options;
    options=optimoptions('patternsearch','Display','iter','Algorithm','classic', ...
        'PollMethod',L.PollMethod,'UseCompletePoll',logical(L.UseCompletePoll), ...
        'ScaleMesh',logical(L.ScaleMesh),'InitialMeshSize',L.InitialMeshSize, ...
        'MaxMeshSize',L.MaxMeshSize,'MeshExpansionFactor',L.MeshExpansionFactor, ...
        'MeshContractionFactor',L.MeshContractionFactor, ...
        'MeshTolerance',L.MeshTolerance,'SearchFcn',[], ...
        'UseParallel',false,'UseVectorized',false,'MaxFunctionEvaluations',125);
else
    error('PFA1:Options','Unknown optimizer block.');
end
end
