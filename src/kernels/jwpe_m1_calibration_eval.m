function e = jwpe_m1_calibration_eval(ctx,theta,cfg,phase)
%JWPE_M1_CALIBRATION_EVAL One source-equivalent M1 forward and sigma fit.
%   Scientific function: never call from static/no-forward validation.
%   OPT permits the accepted PF invalid-negative-state classification. The
%   independent RECHECK is strict and never uses a cached prediction.
theta = double(theta(:).');
phase = upper(string(phase));
assert(any(phase==["OPT","RECHECK"]) && ...
    numel(theta)==5 && all(isfinite(theta)) && theta(1)==cfg.fixedKd && ...
    all(theta>=cfg.lower) && all(theta<=cfg.upper), ...
    'JWPE:Public:Support','Invalid phase or native parameter vector.');
assert(strcmp(ctx.reactor,cfg.reactor) && ...
    ctx.settings.RelTol==cfg.solver.RelTol && ...
    ctx.settings.AbsTol==cfg.solver.AbsTol && ...
    max(ctx.auditTimes_d)==cfg.horizon_d && ...
    ctx.phaseAudit.forcingRows==33 && ctx.phaseAudit.forcingEnd_d==94 && ...
    ~ctx.phaseAudit.responseLeakage && all(isnan(ctx.forcingData.Cout_ug_L)), ...
    'JWPE:Public:Config','Context, forcing or solver policy mismatch.');
if strcmp(cfg.reactor,'CS')
    sim = m1_cs_sim_v1(ctx,theta,m1_cfg_v1());
else
    sim = m1_pf_sim_v1(ctx,theta,m1_cfg_v1());
end
assert(strcmp(sim.model,'M1') && strcmp(sim.reactor,ctx.reactor) && ...
    numel(sim.times_d)==numel(ctx.auditTimes_d) && ...
    max(abs(sim.times_d(:)-ctx.auditTimes_d(:)))<=1e-12 && ...
    max(sim.times_d)==94 && all(isfinite(sim.Cout_SMX)) && ...
    all(isfinite(sim.SMX),'all'), ...
    'JWPE:Public:Forward','Invalid model identity, horizon or finite state.');
e = struct('theta',theta,'key',jwpe_calibration_key(theta), ...
    'eligible',false,'nll',NaN,'sigmaA',NaN,'sigmaP',NaN, ...
    'minSMX',sim.minSMX,'classification','', ...
    'errorFit',struct(),'prediction_ug_L',[],'auditCout_ug_L',[], ...
    'nllPhaseI',NaN,'nllPhaseII',NaN);
if strcmp(cfg.reactor,'PF') && phase=="OPT"
    minimum = pf_min_v2(sim,cfg.invalid.minimumAgreementEpsFactor);
    classification = pf_class_v2(minimum,cfg,'OPT');
    if classification.invalid
        assert(pf_gate_v2(classification.classification,'OPT',cfg));
        e.classification = 'COMPLETE_INVALID_NEGATIVE_STATE';
        e.minimumLocation = minimum;
        return
    end
else
    assert(sim.minSMX>=-2*cfg.solver.AbsTol, ...
        'JWPE:Public:Forward','Negative state exceeds the accepted tolerance.');
end
[found,loc] = ismembertol(ctx.observationTimes_d,sim.times_d,1e-12, ...
    'DataScale',1);
assert(all(found) && numel(loc)==33 && all(loc>0), ...
    'JWPE:Public:Likelihood','Missing observation-time prediction.');
prediction = double(sim.Cout_SMX(loc));
fit = m1pl_sigma_v3(prediction,ctx,cfg,[],'');
assert(strcmp(fit.status,'NUMERICALLY_COMPLETE') && isfinite(fit.nll) && ...
    abs(fit.directRecalculationDelta)<=cfg.likelihood.directTolerance, ...
    'JWPE:Public:Likelihood','Error model did not produce an eligible fit.');
map = m1_map_v1(theta,m1_cfg_v1());
assert(map.krev==0 && map.kSigma==theta(2) && map.Fdir==1 && ...
    map.maxAbsError<=1e-12,'JWPE:Public:Mapping','M1 mapping mismatch.');
e.eligible = true;
e.nll = fit.nll;
e.sigmaA = fit.sigmaA;
e.sigmaP = fit.sigmaP;
e.nllPhaseI = fit.nllPhaseI;
e.nllPhaseII = fit.nllPhaseII;
e.errorFit = fit;
e.classification = fit.classification;
e.prediction_ug_L = prediction;
e.auditCout_ug_L = sim.Cout_SMX;
end
