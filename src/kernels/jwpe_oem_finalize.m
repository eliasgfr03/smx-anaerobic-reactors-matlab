function jwpe_oem_finalize(folder,result)
%JWPE_OEM_FINALIZE Persist compact completed outputs; zero scientific calls.
%   New-folder use only; existing/partial outputs are preserved for review.
assert(strcmp(result.status,'HISTORICAL_OEM_COMPLETE_REVIEW_REQUIRED') && ...
    result.nObs==50 && result.horizon_d==145 && ...
    height(result.comparison)==3 && height(result.starts)==12 && ...
    height(result.pointwise)==150 && height(result.phases)==9 && ...
    ~result.rawBudget.pending,'JWPE:OEM:Incomplete', ...
    'Result is incomplete; do not publish final payloads.');
summary = struct('status',result.status,'role',result.role, ...
    'reactor',result.reactor,'nObs',result.nObs,'nCensored',result.nCensored, ...
    'horizon_d',result.horizon_d,'rawBudget',result.rawBudget, ...
    'identity',result.identity,'scientificPromotion',false, ...
    'phaseIIIUsedOnlyForHistoricalOEM',true,'nativeFminconResume',false);
names = {'result.mat','comparison.csv','starts.csv','pointwise.csv', ...
    'phases.csv','summary.json'};
values = {result,result.comparison,result.starts,result.pointwise, ...
    result.phases,jsonencode(summary)};
kinds = {'mat','table','table','table','table','text'};
for i=1:numel(names)
    assert(~isfile(fullfile(folder,names{i})),'JWPE:OEM:Overwrite', ...
        'Existing scientific output must be preserved.');
end
records = repmat(struct('File','','Bytes',0,'SHA256',''),numel(names),1);
for i=1:numel(names)
    jwpe_run_write(folder,names{i},values{i},kinds{i},false);
    file = fullfile(folder,names{i});
    info = dir(file);
    records(i) = struct('File',names{i},'Bytes',info.bytes, ...
        'SHA256',m1_hash_v1(file,'file'));
end
jwpe_run_write(folder,'manifest.csv',struct2table(records),'table',false);
end
