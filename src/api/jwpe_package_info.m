function info=jwpe_package_info()
%JWPE_PACKAGE_INFO Verify the code inventory and report session requirements.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
manifest=fullfile(root,'code_manifest.json');
[binding,restore]=jwpe_own_environment_v1(manifest);
assert(isa(restore,'onCleanup'));
info=struct('packageRoot',root,'matlabRelease',version('-release'), ...
    'codeFiles',numel(binding.files),'codeHash',binding.codeHash, ...
    'surrogateoptAvailable',exist('surrogateopt','file')==2, ...
    'patternsearchAvailable',exist('patternsearch','file')==2, ...
    'fminconAvailable',exist('fmincon','file')==2, ...
    'scientificExecutionPerformed',false);
end
