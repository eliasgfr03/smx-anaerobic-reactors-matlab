function [job,inputs]=jwpe_prepare_m1(inputFolder,outputRoot,reactor,runID,mode)
%JWPE_PREPARE_M1 Read explicit inputs and save a fixed-Kd M1 execution job.
% mode='demo': synthetic inputs, 24 objective calls plus one raw recheck.
% mode='production': 250 calls plus one recheck. Neither mode runs a model here.
info=jwpe_package_info();
reactor=char(upper(string(reactor)));mode=char(string(mode));
assert(ismember(mode,{'demo','production'}) && ismember(reactor,{'CS','PF'}));
assert(~isempty(regexp(runID,'^[A-Za-z][A-Za-z0-9_-]{0,31}$','once')), ...
    'JWPE:Input:RunID','Use a short run identifier beginning with a letter.');
assert(java.io.File(char(inputFolder)).isAbsolute() && java.io.File(char(outputRoot)).isAbsolute(), ...
    'JWPE:Input:Path','Input and output roots must be absolute.');
cfg=jwpe_m1_calibration_config(reactor);cfg.testOnly=strcmp(mode,'demo');
cfg.surrogate.MaxTime=Inf;
if cfg.testOnly
    cfg.budget.optimizerCalls=24;cfg.budget.rawForwards=25;
    cfg.surrogate.MaxTime=900;cfg.progressEvery=4;
end
paths=struct();roles={'forcing','observations','phases','physical','initialization'};
hashes=strings(1,numel(roles));
for k=1:numel(roles)
    extension='.csv';if k>3,extension='.json';end
    paths.(roles{k})=fullfile(inputFolder,[roles{k} extension]);
    assert(isfile(paths.(roles{k})),'JWPE:Input:Missing','Missing %s',paths.(roles{k}));
    hashes(k)=string(m1_hash_v1(paths.(roles{k}),'file'));
end
spec=struct('reactorID',reactor);data=jwpe_interface_tables_v1(spec,paths);
F=data.forcing;O=data.observations;P=data.phases;
assert(height(O)==33 && height(F)==33 && isequal(O.Time_d,F.Time_d) && ...
    nnz(O.Phase=="I")==17 && nnz(O.Phase=="II")==16 && ...
    all(O.Time_d>0 & O.Time_d<=94) && all((O.Phase=="I") == (O.Time_d<=49)), ...
    'JWPE:Input:Phases','This recipe requires 17/16 Phase-I/II observations through day94.');
assert(isequal(P.Phase,["I";"II"]) && isequal(P.Start_d,[0;49]) && ...
    isequal(P.End_d,[49;94]) && all(P.Use=="calibration"));
assert(all(O.LOD_ug_L==cfg.likelihood.lod_ug_L) && ...
    isequal(O.CensorFlag,O.Cout_ug_L==0) && ...
    ~any(O.Cout_ug_L>0 & O.Cout_ug_L<O.LOD_ug_L), ...
    'JWPE:Input:Censor','Use stored zero for explicitly censored observations; retain raw values separately.');
physical=jsondecode(fileread(paths.physical));
initial=jsondecode(fileread(paths.initialization));
assert(isfield(initial,'dataOrigin'),'JWPE:Input:Origin','Declare dataOrigin in initialization.json.');
if cfg.testOnly
    assert(isfield(initial,'dataOrigin') && strcmp(initial.dataOrigin,'SYNTHETIC'), ...
        'JWPE:Input:Demo','Demo mode requires explicitly synthetic inputs.');
else
    assert(~strcmp(initial.dataOrigin,'SYNTHETIC'), ...
        'JWPE:Input:Production','Synthetic example inputs must remain in demo mode.');
end
assert(isequal(string(initial.parameterNames(:).'),cfg.parameterNames) && ...
    size(initial.points,2)==5 && size(initial.points,1)>=1 && ...
    size(initial.points,1)<=cfg.budget.optimizerCalls && ...
    all(isfinite(initial.points),'all') && ...
    all(initial.points>=cfg.lower & initial.points<=cfg.upper,'all'));
assert(isscalar(initial.seed) && isfinite(initial.seed) && initial.seed>=0 && ...
    initial.seed<=2^32-1 && initial.seed==fix(initial.seed));
cfg.rngSeed=initial.seed;cfg.initialPointCount=size(initial.points,1);
method=struct('RelTol',cfg.solver.RelTol,'AbsTol',cfg.solver.AbsTol,'nodeCount',71);
settings=jwpe_interface_settings_v1(physical,method,'SMX_ORIGINAL');
assert(strcmp(reactor,'CS')==isfield(settings,'tanks_in_series'), ...
    'JWPE:Input:Physics','Reactor and hydraulic model differ.');
if strcmp(reactor,'CS'),assert(isequal(settings.tanks_in_series,[2 2 3]));end
forcing=F(:,{'Time_d','Cin_ug_L'});forcing.Cout_ug_L=nan(33,1);
grid=unique([0:0.5:94,O.Time_d.']).';
ctx=struct('reactor',reactor,'settings',settings,'forcingData',forcing, ...
    'observationTimes_d',O.Time_d,'observed_ug_L',O.Cout_ug_L, ...
    'observationPhaseI',O.Phase=="I",'observationPhaseII',O.Phase=="II", ...
    'auditTimes_d',grid,'start_d',0,'end_d',94,'dataFile',paths.observations, ...
    'harmonization',struct('applied',false), ...
    'phaseAudit',struct('countI',17,'countII',16,'calibrationCount',33, ...
    'forcingRows',33,'forcingEnd_d',94,'responseLeakage',false));
identity=struct('datasetID',m1_hash_v1(char(join(hashes,'')),'text'), ...
    'methodID',m1_hash_v1(jsonencode(cfg),'text'),'codeHash',info.codeHash, ...
    'dataClassification',char(string(initial.dataOrigin)));
inputs=struct('cfg',cfg,'context',ctx,'initialPoints',initial.points,'identity',identity);
folder=fullfile(outputRoot,'calibration_m1_fixed',reactor,runID);
assert(~isfolder(folder) && ~isfile(folder),'JWPE:Input:Overwrite','Choose a new run identifier.');
executionMode='production';if cfg.testOnly,executionMode='test';end
payload=struct('schemaVersion','JWPE_OWN_EXECUTION_v1','analysis','calibration_m1_fixed', ...
    'reactor',reactor,'mode',executionMode,'runID',runID,'folder',folder, ...
    'identity',identity,'inputs',inputs,'action','new','executeScientific',true);
jobFile=fullfile(outputRoot,'jobs',[reactor '_' runID '.mat']);
job=jwpe_save_job(payload,jobFile);
end
